import numpy as np

# =========================================================
# Quiz13-1 : 삼성 주가 투자 리스크 분석
# =========================================================
# 15일 종가와 누적 최대값을 넘파이 배열로 생성
stock = np.array(
    [68000, 68500, 69000, 70000, 69500,
     69000, 68000, 67500, 67000, 66000,
     66500, 67000, 68000, 68500, 69000],
    dtype=int
)

cumMax = np.array(
    [68000, 68500, 69000, 70000, 70000,
     70000, 70000, 70000, 70000, 70000,
     70000, 70000, 70000, 70000, 70000],
    dtype=int
)

print("<삼성 주가>")
print(stock)
print("<누적최대값>")
print(cumMax)

# 낙폭률 = (종단가 - 누적최대값) / 누적최대값   (브로드캐스팅 이용)
drawdown = (stock - cumMax) / cumMax

print("<낙폭률>")
print(drawdown)   # 여기서는 소수점 두 자리 처리 안 해도 됨 (문제 조건)

# 최대 낙폭률(가장 작은 값)과 그 날의 인덱스
max_drop_rate = drawdown.min()       # 예: -0.06
max_drop_idx = np.argmin(drawdown)   # 0부터 시작 → 일수는 +1
day = max_drop_idx + 1

# 리스크 등급 판단
# 위험: 20% 이상, 주의: 10% 이상 20% 미만, 안전: 10% 미만
abs_rate = abs(max_drop_rate)

if abs_rate >= 0.2:
    level = "위험"
elif abs_rate >= 0.1:
    level = "주의"
else:
    level = "안전"

print("최대낙폭 일={}일".format(day))
# 여기서는 소수점 두 자리 처리해야 함 (문제 조건)
print("최대낙폭 률={:.2f}({})".format(max_drop_rate, level))

