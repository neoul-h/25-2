# 넘파이 배열로 변환 (None이 있어서 일단 object 타입으로)
salary_obj = np.array(data, dtype=object)

# None이 아닌 값들에 대한 마스크
not_none_mask = salary_obj != None

# None이 아닌 값들만 골라서 float 배열로 변환
valid_salary = salary_obj[not_none_mask].astype(float)

# 현재 데이터의 최소값과 최대값
min_val = valid_salary.min()
max_val = valid_salary.max()

# None 값이 들어있는 인덱스 찾기 (힌트 ②)
none_idx = np.where(salary_obj == None)

# None이 있는 개수만큼 [최소값, 최대값] 사이의 난수 생성
# (힌트 ① 조건에 맞게 랜덤으로 채우기)
fill_values = np.random.uniform(min_val, max_val, size=len(none_idx[0]))

# None 자리에 랜덤 값 대입
salary_obj[none_idx] = fill_values

# 전부 숫자가 되었으므로 float → int 형으로 변환
salary_int = salary_obj.astype(int)

# 전체 연봉 평균 계산 (int형으로 출력해야 함)
avg_salary = int(salary_int.mean())

